"use client";

import { useEffect, useMemo, useState } from "react";
import { useSearchParams } from "next/navigation";
import type { SectionProps } from "../../../types/section";
import { site } from "../data/categorySite";
import { useOptionalPreview } from "../../context/PreviewContext";
import {
  buildReadableNgoEventBody,
  findNgoEvent,
  isAutoGeneratedEventBody,
  isMismatchedEventPackBody,
  NGO_EVENT_DETAIL_SLUG_EVENT,
  readNgoEventDetailSlug,
  resolveNgoEventSlug,
} from "../../../lib/ngoEventDetails";
import {
  DEFAULT_EVENT_DETAIL_LAYOUT,
  normalizeEventDetailLayout,
} from "../../../lib/eventLayouts";
import NgoEventDetailArticle from "./NgoEventDetailArticle";

const FALLBACK_IMAGE =
  "/categories/ngo/template1/children-speaking-holding-book.jpg";

type EventListItem = Record<string, unknown>;

const text = (value: unknown, fallback = "") =>
  typeof value === "string" && value.trim() ? value.trim() : fallback;

export default function NgoEventDetail1({ data: customData }: SectionProps) {
  const preview = useOptionalPreview();
  const searchParams = useSearchParams();
  const sectionData = (customData || {}) as Record<string, unknown>;
  const pageParam = (searchParams.get("page") || "").trim().toLowerCase();
  const slugFromRoute = pageParam.startsWith("event-details-")
    ? pageParam.slice("event-details-".length)
    : "";

  const listingEvents = useMemo(() => {
    const pools: EventListItem[][] = [];
    if (Array.isArray(sectionData.items) && sectionData.items.length) {
      pools.push(sectionData.items as EventListItem[]);
    }
    if (Array.isArray(site.events?.items) && site.events.items.length) {
      pools.push(site.events.items as EventListItem[]);
    }
    if (Array.isArray(site.eventPage?.items) && site.eventPage.items.length) {
      pools.push(site.eventPage.items as EventListItem[]);
    }
    const byKey = new Map<string, EventListItem>();
    for (const pool of pools) {
      for (const item of pool) {
        const key = resolveNgoEventSlug({
          id: item.id as string | number | undefined,
          title: text(item.title),
        });
        if (!key) continue;
        const existing = byKey.get(key);
        if (!existing) {
          byKey.set(key, item);
          continue;
        }
        const existingContent = text(existing.content);
        const nextContent = text(item.content);
        if (!existingContent && nextContent) {
          byKey.set(key, { ...existing, ...item, content: nextContent });
        } else if (nextContent && nextContent.length > existingContent.length) {
          byKey.set(key, { ...existing, ...item, content: nextContent });
        } else {
          byKey.set(key, {
            ...item,
            ...existing,
            content: existingContent || nextContent,
          });
        }
      }
    }
    return Array.from(byKey.values());
  }, [sectionData.items]);

  const [selectedSlug, setSelectedSlug] = useState(slugFromRoute);

  useEffect(() => {
    if (slugFromRoute) setSelectedSlug(slugFromRoute);
  }, [slugFromRoute]);

  useEffect(() => {
    const syncSlug = (event?: Event) => {
      const fromClick = (event as CustomEvent<{ slug?: string }> | undefined)
        ?.detail?.slug;
      if (typeof fromClick === "string" && fromClick.trim()) {
        setSelectedSlug(fromClick.trim());
        return;
      }
      const fromStore = readNgoEventDetailSlug();
      if (fromStore) setSelectedSlug(fromStore);
    };
    syncSlug();
    window.addEventListener(NGO_EVENT_DETAIL_SLUG_EVENT, syncSlug);
    return () =>
      window.removeEventListener(NGO_EVENT_DETAIL_SLUG_EVENT, syncSlug);
  }, [preview?.currentPage]);

  const activeSlug = slugFromRoute || selectedSlug;
  const selectedEvent =
    findNgoEvent(listingEvents, activeSlug) || listingEvents[0] || null;

  if (!selectedEvent) {
    return (
      <main className="bg-white" data-editor-section-label="Event Details">
        <section className="py-16 px-4 text-center text-gray-500">
          No event found for this detail page.
        </section>
      </main>
    );
  }

  const title = text(selectedEvent.title, "Event");
  const image = text(selectedEvent.image, FALLBACK_IMAGE);
  const date = text(selectedEvent.date) || text(selectedEvent.eventDate);
  const location = text(selectedEvent.location);
  const excerpt =
    text(selectedEvent.desc) ||
    text(selectedEvent.description) ||
    text(selectedEvent.excerpt) ||
    [date, location].filter(Boolean).join(" · ");
  const rawContent = text(selectedEvent.content);
  const contentSafe =
    rawContent &&
    !isAutoGeneratedEventBody(rawContent) &&
    !isMismatchedEventPackBody(rawContent, title, site.eventDetails) &&
    !/About Event Details/i.test(rawContent) &&
    !/Why Event Details matters/i.test(rawContent)
      ? rawContent
      : "";
  const packTitle = text(
    (site.eventDetails?.content as { title?: string } | undefined)?.title,
  );
  const usePack =
    Boolean(site.eventDetails) &&
    Boolean(packTitle) &&
    packTitle.toLowerCase() === title.toLowerCase();
  const content = buildReadableNgoEventBody(
    {
      title,
      category: text(selectedEvent.category, "Event"),
      excerpt,
      desc: excerpt,
      content: contentSafe,
      location,
    },
    usePack && !contentSafe ? site.eventDetails : null,
  );

  const layout = normalizeEventDetailLayout(
    text(selectedEvent.layout) ||
      text(selectedEvent.detailLayout) ||
      text(sectionData.layout) ||
      text(sectionData.detailLayout) ||
      DEFAULT_EVENT_DETAIL_LAYOUT,
  );

  return (
    <main
      className="bg-white"
      data-editor-section-label="Event Details"
      data-editor-fields="title,category,excerpt,content,image,layout"
      data-active-event-slug={activeSlug}
    >
      <NgoEventDetailArticle
        key={`${title}-${layout}-${activeSlug}`}
        eventItem={{
          title,
          category: text(selectedEvent.category, "Event"),
          excerpt,
          content,
          image,
          layout,
          eventDate: date,
          eventTime: text(selectedEvent.eventTime),
          eventType: selectedEvent.eventType === "past" ? "past" : "upcoming",
        }}
      />
    </main>
  );
}
