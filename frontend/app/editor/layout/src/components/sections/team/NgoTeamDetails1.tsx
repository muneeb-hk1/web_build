"use client";

import React, { useEffect, useMemo, useState } from "react";
import { useSearchParams } from "next/navigation";
import { site } from "../data/categorySite";
import type { SectionProps } from "../../../types/section";
import { useOptionalPreview } from "../../context/PreviewContext";
import {
  buildReadableNgoTeamBody,
  findNgoTeamMember,
  isAutoGeneratedTeamBody,
  isMismatchedTeamPackBody,
  NGO_TEAM_DETAIL_SLUG_EVENT,
  readNgoTeamDetailSlug,
  resolveNgoTeamSlug,
} from "../../../lib/ngoTeamDetails";
import {
  DEFAULT_TEAM_DETAIL_LAYOUT,
  normalizeTeamDetailLayout,
} from "../../../lib/teamLayouts";
import NgoTeamDetailArticle from "./NgoTeamDetailArticle";

const FALLBACK_IMAGE = "/categories/ngo/template1/team/women1.png";

type TeamListItem = Record<string, unknown>;

const text = (value: unknown, fallback = "") =>
  typeof value === "string" && value.trim() ? value.trim() : fallback;

export default function NgoTeamDetails1({ data: customData }: SectionProps) {
  const preview = useOptionalPreview();
  const searchParams = useSearchParams();
  const sectionData = (customData || {}) as Record<string, unknown>;
  const pageParam = (searchParams.get("page") || "").trim().toLowerCase();
  const slugFromRoute = pageParam.startsWith("team-details-")
    ? pageParam.slice("team-details-".length)
    : "";

  const listingMembers = useMemo(() => {
    const pools: TeamListItem[][] = [];
    if (Array.isArray(sectionData.members) && sectionData.members.length) {
      pools.push(sectionData.members as TeamListItem[]);
    }
    if (Array.isArray(site.team?.members) && site.team.members.length) {
      pools.push(site.team.members as TeamListItem[]);
    }
    if (Array.isArray(site.teamPage?.members) && site.teamPage.members.length) {
      pools.push(site.teamPage.members as TeamListItem[]);
    }
    const byKey = new Map<string, TeamListItem>();
    for (const pool of pools) {
      for (const member of pool) {
        const key = resolveNgoTeamSlug({
          id: member.id as string | number | undefined,
          name: text(member.name),
          title: text(member.title),
        });
        if (!key) continue;
        const existing = byKey.get(key);
        if (!existing) {
          byKey.set(key, member);
          continue;
        }
        // Prefer rows that already have rich Content from the template/manager.
        const existingContent = text(existing.content);
        const nextContent = text(member.content);
        if (!existingContent && nextContent) {
          byKey.set(key, { ...existing, ...member, content: nextContent });
        } else if (nextContent && nextContent.length > existingContent.length) {
          byKey.set(key, { ...existing, ...member, content: nextContent });
        } else {
          byKey.set(key, {
            ...member,
            ...existing,
            content: existingContent || nextContent,
          });
        }
      }
    }
    return Array.from(byKey.values());
  }, [sectionData.members]);

  const [selectedSlug, setSelectedSlug] = useState(slugFromRoute);

  useEffect(() => {
    if (slugFromRoute) setSelectedSlug(slugFromRoute);
  }, [slugFromRoute]);

  useEffect(() => {
    const syncSlug = (event?: Event) => {
      const fromClick = (event as CustomEvent<{ slug?: string }> | undefined)
        ?.detail?.slug;
      if (typeof fromClick === "string" && fromClick.trim()) {
        setSelectedSlug(fromClick.trim());
        return;
      }
      const fromStore = readNgoTeamDetailSlug();
      if (fromStore) setSelectedSlug(fromStore);
    };
    syncSlug();
    window.addEventListener(NGO_TEAM_DETAIL_SLUG_EVENT, syncSlug);
    return () =>
      window.removeEventListener(NGO_TEAM_DETAIL_SLUG_EVENT, syncSlug);
  }, [preview?.currentPage]);

  const activeSlug = slugFromRoute || selectedSlug;
  const selectedMember = useMemo(
    () => findNgoTeamMember(listingMembers, activeSlug),
    [listingMembers, activeSlug],
  );

  const member = selectedMember || (!activeSlug ? listingMembers[0] : null);
  const layout = normalizeTeamDetailLayout(
    text(member?.layout) ||
      text(member?.detailLayout) ||
      text(sectionData.layout) ||
      text(sectionData.detailLayout) ||
      DEFAULT_TEAM_DETAIL_LAYOUT,
  );

  if (!member) {
    return (
      <main
        className="bg-white"
        data-editor-section-label="Team Details"
        data-active-team-slug={activeSlug}
      >
        <section className="py-16 px-4 text-center text-gray-500">
          No team member found for this detail page.
        </section>
      </main>
    );
  }

  const title = text(member.name) || text(member.title, "Team member");
  const role = text(member.role) || text(member.category, "Volunteer");
  const image = text(member.image, FALLBACK_IMAGE);
  const rawContent = text(member.content);
  const contentSafe =
    rawContent &&
    !isAutoGeneratedTeamBody(rawContent) &&
    !isMismatchedTeamPackBody(rawContent, title, site.teamDetails) &&
    !/About Team Details/i.test(rawContent) &&
    !/Why Team Details matters/i.test(rawContent)
      ? rawContent
      : "";
  const packName = text(site.teamDetails?.name);
  const usePack =
    Boolean(site.teamDetails) &&
    Boolean(packName) &&
    packName.toLowerCase() === title.toLowerCase();
  const content = buildReadableNgoTeamBody(
    {
      title,
      name: title,
      role,
      category: role,
      excerpt: role,
      content: contentSafe,
    },
    usePack && !contentSafe ? site.teamDetails : null,
  );

  return (
    <main
      className="bg-white"
      data-editor-section-label="Team Details"
      data-editor-fields="title,category,excerpt,content,image,layout"
      data-active-team-slug={
        activeSlug ||
        resolveNgoTeamSlug({
          id: member.id as string | number | undefined,
          name: title,
        })
      }
    >
      <NgoTeamDetailArticle
        key={`${title}-${layout}-${activeSlug || member.id}`}
        teamMember={{
          title,
          category: role,
          excerpt: role,
          content,
          image,
          layout,
        }}
      />
    </main>
  );
}
