const iconLookupKeys = (iconName: string) => {
  const trimmed = iconName.trim();
  const keys = new Set<string>([trimmed, trimmed.toLowerCase()]);
  const withoutPrefix = trimmed.replace(
    /^(Fi|Fa|Lu|Bs|Hi|Io|Icon)/,
    "",
  );
  keys.add(withoutPrefix);
  keys.add(withoutPrefix.toLowerCase());
  const kebab = withoutPrefix
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
  keys.add(kebab);
  return [...keys].filter(Boolean);
};

const resolveIcon = (
  map: Record<string, NgoIconComponent>,
  iconName: string | undefined,
  fallback: NgoIconComponent,
): NgoIconComponent => {
  if (!iconName) return fallback;
  for (const key of iconLookupKeys(iconName)) {
    if (map[key]) return map[key];
  }
  return fallback;
};

export const normalizeNgoIconId = (iconName?: string) => {
  const keys = iconLookupKeys(iconName || "");
  return keys[keys.length - 1] || "";
};

export const renderNgoIcon = (
  iconName: string | undefined,
  className = "h-5 w-5",
  fallback: NgoIconComponent = HandHeart as NgoIconComponent,
) => {
  const IconComp = resolveIcon(ngoIconMap, iconName, fallback);
  return <IconComp className={className} aria-hidden />;
};

export const renderNgoSocialIcon = (
  iconName: string | undefined,
  className = "h-4 w-4",
  fallback: NgoIconComponent = FaFacebookF,
) => {
  const IconComp = resolveIcon(ngoSocialIconMap, iconName, fallback);
  return <IconComp className={className} aria-hidden />;
};
