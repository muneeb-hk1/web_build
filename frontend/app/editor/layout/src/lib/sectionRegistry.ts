export function resolveSectionComponent(
  variantKey: string,
): ComponentType<SectionProps> | undefined {
  if (sectionRegistry[variantKey]) return sectionRegistry[variantKey];
  const lower = variantKey.toLowerCase();
  const matchKey = Object.keys(sectionRegistry).find(
    (key) => key.toLowerCase() === lower,
  );
  return matchKey ? sectionRegistry[matchKey] : undefined;
}

/** Fields the selected layout component paints. Missing means the older shared popup. */
export function getComponentEditorFields(variant: string): string[] | null {
  const component = resolveSectionComponent(variant) as
    | (ComponentType<SectionProps> & { editorFields?: readonly string[] })
    | undefined;
  const fields = component?.editorFields;
  return fields?.length ? [...fields] : null;
}
